# Day 1: Python Strings Practice
# Goal: Master string manipulation.

my_career_goal = "I want to be an Applied AI Researcher"

# Practice 1: Uppercase
print(my_career_goal.upper())

# Practice 2: Count "AI"
print(f"AI appears {my_career_goal.count('AI')} times.")

# Practice 3: Replace
modified_goal = my_career_goal.replace("Applied", "Elite")
print(f"Goal: {modified_goal}")

# Practice 4: Slicing
# Goal: Print only the last word "Researcher"
print(my_career_goal[-10:])
